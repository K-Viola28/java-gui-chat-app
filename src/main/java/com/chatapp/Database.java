
package com.chatapp;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;

public class Database {

    private static final String DATABASE_URL;

    static {
        try {
            Path dataDirectory = Path.of("data").toAbsolutePath().normalize();
            Files.createDirectories(dataDirectory);

            Path databaseFile = dataDirectory.resolve("chatdb");
            DATABASE_URL = "jdbc:h2:file:" + databaseFile;
        } catch (IOException e) {
            throw new ExceptionInInitializerError(e);
        }
    }

    public Database() throws SQLException {
        initializeDatabase();
    }

    private Connection connect() throws SQLException {
        return DriverManager.getConnection(
                DATABASE_URL, "sa", ""
        );
    }

    private void initializeDatabase() throws SQLException {
        String sql = """
                CREATE TABLE IF NOT EXISTS chat_messages (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    sender VARCHAR(50) NOT NULL,
                    content VARCHAR(2000) NOT NULL,
                    message_type VARCHAR(20) NOT NULL,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
                """;

        try (Connection connection = connect();
             Statement statement = connection.createStatement()) {

            statement.execute(sql);
        }
    }

    public void saveMessage(Message message) throws SQLException {
        String sql = """
                INSERT INTO chat_messages
                    (sender, content, message_type)
                VALUES (?, ?, ?)
                """;

        String type = message instanceof SystemMessage
                ? "system" : "text";

        try (Connection connection = connect();
             PreparedStatement statement =
                     connection.prepareStatement(sql)) {

            statement.setString(1, message.getSender());
            statement.setString(2, message.getContent());
            statement.setString(3, type);

            statement.executeUpdate();
        }
    }

    public List<Message> getAllMessages() throws SQLException {
        List<Message> messages = new ArrayList<>();

        String sql = """
                SELECT sender, content, message_type
                FROM chat_messages
                ORDER BY id
                """;

        try (Connection connection = connect();
             Statement statement = connection.createStatement();
             ResultSet result = statement.executeQuery(sql)) {

            while (result.next()) {
                String sender = result.getString("sender");
                String content = result.getString("content");
                String type = result.getString("message_type");

                if ("system".equals(type)) {
                    messages.add(new SystemMessage(content));
                } else {
                    messages.add(new TextMessage(sender, content));
                }
            }
        }

        return messages;
    }
}
